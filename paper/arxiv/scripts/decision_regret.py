#!/usr/bin/env python3
"""Regenerate retrospective decision regret from the retained trusted join.

No new measurements or qualification verdicts are produced. Both the JSON
report and the typeset table must regenerate from the hash-bound aggregate.
Run from a repository checkout; --check compares without writing.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import sys
from pathlib import Path

SOURCE = Path(__file__).resolve().parents[1]
ROOT = SOURCE.parents[1]
sys.path.insert(0, str(ROOT / "src"))

from commcanary.services.fidelity import score_fidelity  # noqa: E402

PUBLICATION = "experiments/rostam/results/publications/trusted-join-core-shared-overlap-primary"
LABELS = {
    "full": "W-full",
    "micro": "W-micro",
    "canary-param": "W-canary",
    "canary-overlap": "W-canary-overlap",
    "shared-overlap": "W-shared-overlap",
}
IMPLEMENTATION_COMMIT = "cefad5a086b4723755bbe33b33e96f9f3a2c8e36"


def build() -> dict:
    snapshot = json.loads((SOURCE / "evidence/verified_metrics.json").read_text())
    inputs = {}
    for suffix in ("aggregate.csv", "aggregate.json"):
        relative = f"{PUBLICATION}/{suffix}"
        data = (ROOT / relative).read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        if digest != snapshot["source_files"][relative]:
            raise SystemExit(f"retained evidence digest mismatch: {relative}")
        inputs[relative] = digest
    aggregate = json.loads((ROOT / PUBLICATION / "aggregate.json").read_text())
    if not aggregate["completeness"]["complete"] or aggregate["selected_cell_count"] != 280:
        raise SystemExit("expected the complete 280-cell trusted join")

    cells = {label: {} for label in LABELS.values()}
    with (ROOT / PUBLICATION / "aggregate.csv").open(newline="") as stream:
        rows = sorted(csv.DictReader(stream), key=lambda row: row["cell_id"])
    for row in rows:
        if row["record_kind"] == "measurement" and row["workload_id"] in LABELS:
            configs = cells[LABELS[row["workload_id"]]]
            configs.setdefault(row["configuration_id"], []).append(float(row["value_us"]))
    measurement_sets = []
    for label, configurations in cells.items():
        if len(configurations) != 8 or any(len(values) != 5 for values in configurations.values()):
            raise SystemExit(f"{label}: expected eight configurations with five repetitions each")
        measurement_sets.append(
            {
                "format": "commcanary.measurement_set.v1",
                "name": label,
                "role": "reference" if label == "W-full" else "proxy",
                "metric": "median_us",
                "direction": "lower_is_better",
                "measurements": dict(sorted(configurations.items())),
            }
        )
    report = score_fidelity(
        measurement_sets,
        confidence=0.95,
        bootstrap_resamples=4000,
        seed=20261004,
        minimum_replicates=5,
    )
    for proxy in report["proxies"]:
        expected = aggregate["claims"]["agreements"][f"{proxy['name']}_vs_W-full"]["agree"]
        if proxy["ranking_quality"]["pairwise_decision_agreement"] != expected / 28:
            raise SystemExit(f"{proxy['name']}: pair agreement differs from retained analysis")
    return {
        "schema": "commcanary.paper.decision_regret.v1",
        "evidence_commit": snapshot["paper"]["evidence_commit"],
        "implementation_commit": IMPLEMENTATION_COMMIT,
        "inputs": inputs,
        "interpretation": "Retrospective analysis of retained repetitions; no new physical run or qualification verdict.",
        "measurement_sets": measurement_sets,
        "report": report,
    }


def table(data: dict) -> str:
    rows = {row["name"]: row for row in data["report"]["proxies"]}
    lines = [
        "% Generated by scripts/decision_regret.py; do not edit.",
        r"\begin{tabular}{@{}lrrrrr@{}}",
        r"\toprule",
        r"Proxy & $r_1$ (\%) & 95\% interval & $r_2$ (\%) & $r_3$ (\%) & Worst rank \\",
        r"\midrule",
    ]
    for name in list(LABELS.values())[1:]:
        row = rows[name]
        ci = row["regret_at_1_confidence_interval"]
        shortlists = {item["k"]: item["regret_pct"] for item in row["regret_at_k"]}
        lines.append(
            rf"\wname{{{name[2:]}}} & {row['regret_at_1_pct']:.2f} & "
            rf"{ci['lower_pct']:.2f}--{ci['upper_pct']:.2f} & "
            rf"{shortlists[2]:.2f} & {shortlists[3]:.2f} & "
            rf"{row['disaster_detection']['proxy_rank']}/8 \\"
        )
    return "\n".join(lines + [r"\bottomrule", r"\end{tabular}", ""])


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    data = build()
    outputs = {
        SOURCE / "evidence/decision_regret.json": json.dumps(data, indent=2, sort_keys=True) + "\n",
        SOURCE / "tables/decision-regret.tex": table(data),
    }
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"{path} does not match a fresh regeneration")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(
        "verified decision-regret JSON and LaTeX table" if args.check else "wrote decision-regret JSON and LaTeX table"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
